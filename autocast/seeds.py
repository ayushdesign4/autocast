class SceneDict(TypedDict, total=False):
    idx: int
    scene_number: int
    title_hindi: str
    characters_hindi: str
    location_hindi: str
    action_hindi: str
    dialogue_hindi: str
    narration: str
    image_prompt: str
    video_prompt: str
    motion: str
    caption: str
    duration_s: float
    has_native_audio: bool
    status: str

@dataclass(frozen=True)
class Seed:
    title: str
    characters: tuple[dict, ...]
    shots: tuple[SceneDict, ...]

    @property
    def script(self) -> str:
        return " ".join(shot["narration"] for shot in self.shots)

